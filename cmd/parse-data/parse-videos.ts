import fs from "node:fs";
import path from "node:path";

export interface VideoItem {
  whenAdded: string;
  id: string;
  title: string;
  url: string;
  summary: string;
}

export function parseVideos(): void {
  const inputFilePath = path.resolve("data", "videos.dpod.txt");
  const outputDir = path.resolve("js", "data");
  const outputFilePath = path.join(outputDir, "videos.js");

  if (!fs.existsSync(inputFilePath)) {
    console.warn(`[parse-videos] Input file not found: ${inputFilePath}`);
    return;
  }

  const fileContent = fs.readFileSync(inputFilePath, "utf-8");
  const lines = fileContent.split(/\r?\n/);

  const videos: VideoItem[] = [];

  for (const line of lines) {
    const trimmedLine = line.trim();
    if (!trimmedLine || trimmedLine.startsWith("#")) {
      continue;
    }

    const parts = trimmedLine.split(";");
    if (parts.length >= 5) {
      // Format: whenAdded; id; title; url; summary
      const whenAdded = parts[0].trim();
      const id = parts[1].trim();
      const title = parts[2].trim();
      const url = parts[3].trim();
      const summary = parts.slice(4).join(";").trim();

      if (id && url && title) {
        videos.push({ whenAdded, id, title, url, summary });
      }
    } else if (parts.length === 4) {
      // Fallback format without whenAdded: id; title; url; summary
      const id = parts[0].trim();
      const title = parts[1].trim();
      const url = parts[2].trim();
      const summary = parts.slice(3).join(";").trim();

      if (id && url && title) {
        videos.push({ whenAdded: "", id, title, url, summary });
      }
    }
  }

  // Sort videos newest to oldest by whenAdded timestamp
  videos.sort((a, b) => {
    if (!a.whenAdded) return 1;
    if (!b.whenAdded) return -1;
    return b.whenAdded.localeCompare(a.whenAdded);
  });

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const jsContent = `// Auto-generated by cmd/parse-data.ts - DO NOT EDIT MANUALLY\nexport const videos = ${JSON.stringify(
    videos,
    null,
    2
  )};\n`;

  fs.writeFileSync(outputFilePath, jsContent, "utf-8");
  console.log(`[parse-videos] Parsed ${videos.length} videos -> ${outputFilePath}`);
}
